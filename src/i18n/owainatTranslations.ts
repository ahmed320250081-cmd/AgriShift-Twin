export function translateCrop(crop: CropType, lang: Language): string {
  return CROP_LABELS[lang][crop] ?? crop;
}

export function translateGrowthStage(stage: string, lang: Language): string {
  if (lang === 'en') return stage;
  return GROWTH_STAGE_AR[stage] ?? stage;
}

export function translateOperator(name: string, lang: Language): string {
  if (lang === 'en') return name;
  return OPERATOR_NAMES_AR[name] ?? name;
}

export function translateRole(role: UserRole, lang: Language): string {
  if (lang === 'ar') {
    return role === 'farm_manager' ? 'مدير المزرعة' : 'مشغل ميداني';
  }
  return role === 'farm_manager' ? 'Farm Manager' : 'Field Operator';
}

export function translateLogCategory(
  category: FieldLogEntry['category'],
  lang: Language,
): string {
  const map: Record<Language, Record<FieldLogEntry['category'], string>> = {
    en: {
      irrigation: 'Irrigation Action',
      nozzle_check: 'Nozzle Inspection',
      soil_sample: 'Soil Calibration',
      weather_action: 'Weather Advisory',
    },
    ar: {
      irrigation: 'إجراء ري',
      nozzle_check: 'فحص الفوهات',
      soil_sample: 'معايرة التربة',
      weather_action: 'إجراء مناخي',
    },
  };
  return map[lang][category];
}

export function translateLogNote(note: string, lang: Language): string {
  if (lang === 'en') return note;
  return SEED_LOG_NOTES_AR[note] ?? note;
}

